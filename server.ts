import express from 'express';
import { createServer as createViteServer } from 'vite';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

async function startServer() {
  const app = express();
  const PORT = process.env.PORT ? parseInt(process.env.PORT) : 3000;

  app.use(express.json({ limit: '50mb' }));

  // Shared Gemini client
  const apiKey = process.env.GEMINI_API_KEY;
  let ai: GoogleGenAI | null = null;
  if (apiKey) {
    ai = new GoogleGenAI({
      apiKey,
      httpOptions: {
        headers: {
          'User-Agent': 'aistudio-build',
        },
      },
    });
  }

  // API Route for Forensic Analysis of Image or Video frames
  app.post('/api/analyze', async (req, res) => {
    try {
      const { mediaType, base64Data, mediaUrl, mimeType, filename } = req.body;

      let cleanBase64 = '';
      let targetMimeType = mimeType || 'image/jpeg';

      if (base64Data && base64Data.startsWith('data:')) {
        const matches = base64Data.match(/^data:([^;]+);base64,(.+)$/);
        if (matches) {
          targetMimeType = matches[1];
          cleanBase64 = matches[2];
        } else {
          cleanBase64 = base64Data.replace(/^data:[^;]+;base64,/, '');
        }
      } else if (base64Data) {
        cleanBase64 = base64Data;
      } else if (mediaUrl && mediaUrl.startsWith('http')) {
        // Fetch remote media
        try {
          const fetchRes = await fetch(mediaUrl);
          const arrayBuf = await fetchRes.arrayBuffer();
          cleanBase64 = Buffer.from(arrayBuf).toString('base64');
          const headerType = fetchRes.headers.get('content-type');
          if (headerType) targetMimeType = headerType;
        } catch (fetchErr) {
          console.warn('Failed to fetch remote mediaUrl:', fetchErr);
        }
      }

      if (!cleanBase64) {
        res.status(400).json({ error: 'Missing or unresolvable image data in request' });
        return;
      }

      if (!ai) {
        // Return structured fallback response indicating heuristic mode
        res.json({
          status: 'fallback',
          message: 'AI server key not configured. Heuristic engine active.',
        });
        return;
      }

      const prompt = `You are an elite digital forensic investigator specializing in identifying AI synthetic media and deepfakes (Midjourney, Flux, Stable Diffusion, DALL-E, Sora, Runway, Kling, FaceSwap).

Perform an objective, scientifically rigorous forensic analysis on the provided media (${mediaType || 'image'}, file: ${filename || 'input'}).

Determine:
1. Overall probability that this is AI generated (0-100%).
   - If this is a real optical photo taken by a physical camera with authentic natural skin pores, natural noise, physically coherent lighting/reflections: give a low score (e.g. 5-25%).
   - If this is generated by an AI diffusion or video model: identify the subtle artifacts (plastic texture, iris asymmetry, impossible geometry, prompt hallucinations, frequency banding) and give an accurate high score (e.g. 75-98%).
2. Primary verdict: MUST be one of:
   - 'Likely AI-Generated' (if probability >= 70%)
   - 'Suspicious Synthetic Media' (if probability between 45% and 69%)
   - 'Authentic Camera Capture' (if probability <= 30%)
   - 'Inconclusive / Mixed' (if probability between 31% and 44%)
3. Confidence score (0-100%).
4. Suspected generative model/engine (e.g. 'Midjourney v6.1', 'Flux.1 Schnell', 'Stable Diffusion XL', 'DALL-E 3', 'Runway Gen-3', or 'Digital CMOS Camera Sensor (Canon/Sony/Apple)').
5. Detailed scores (0-100% where higher means more synthetic/anomalous):
   - spectralAnomaly: frequency/FFT checkerboard artifacts or latent upsampler signatures
   - skinTextureSmoothing: synthetic waxiness, smoothed pores, or airbrushed sheen
   - anatomicalAnomalies: hands, eyes, teeth, iris reflections, structural geometry
   - lightingPhysics: shadow angle mismatches, inconsistent specular catchlights
   - edgeArtifacts: boundary blur halos, chromatic aberrations, latent blending
   - temporalJitter: (for video frames) frame morphing or background boiling
6. Key observations: 3-5 concise bullet points citing concrete visual forensic evidence.
7. Executive summary: 2-3 sentences summarizing the forensic findings.

Return ONLY a valid JSON object matching this schema:
{
  "aiProbability": number,
  "verdict": string,
  "confidence": number,
  "suspectedModel": string,
  "metrics": {
    "spectralAnomaly": number,
    "skinTextureSmoothing": number,
    "anatomicalAnomalies": number,
    "lightingPhysics": number,
    "edgeArtifacts": number,
    "temporalJitter": number
  },
  "observations": string[],
  "executiveSummary": string
}`;

      const response = await ai.models.generateContent({
        model: 'gemini-3.8-flash',
        contents: {
          parts: [
            {
              inlineData: {
                mimeType: targetMimeType,
                data: cleanBase64,
              },
            },
            {
              text: prompt,
            },
          ],
        },
        config: {
          responseMimeType: 'application/json',
          temperature: 0.1,
        },
      });

      const responseText = response.text?.trim() || '{}';
      const parsed = JSON.parse(responseText);

      res.json({
        status: 'success',
        source: 'gemini-3.8-flash',
        ...parsed,
      });
    } catch (err: any) {
      console.error('Forensic analysis error:', err);
      res.status(500).json({
        error: err.message || 'Forensic analysis failed',
        status: 'error',
      });
    }
  });

  // Newsletter subscription mock API endpoint
  app.post('/api/newsletter', (req, res) => {
    const { email } = req.body;
    if (!email || !email.includes('@')) {
      res.status(400).json({ error: 'Valid email required' });
      return;
    }
    res.json({ success: true, message: 'Subscribed to Veritas AI updates' });
  });

  // Dev mode Vite middleware or Production static files
  if (process.env.NODE_ENV === 'production') {
    app.use(express.static(path.join(__dirname, 'dist')));
    app.get('*', (_req, res) => {
      res.sendFile(path.join(__dirname, 'dist', 'index.html'));
    });
  } else {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`Veritas AI Server running on http://localhost:${PORT}`);
  });
}

startServer().catch((err) => {
  console.error('Failed to start server:', err);
  process.exit(1);
});
